// Преобразование строки в число
// Группа: Строки
// Описание: Переводит строку в число и обратно.
// Ожидаемый вывод: 43; 3.14; 100!
// Пояснения:
//   parseFloat — читает число с начала строки, остальное игнорирует.

const текст = '42';
console.log(Number(текст) + 1);
console.log(parseFloat('3.14abc'));
console.log(String(100) + '!');

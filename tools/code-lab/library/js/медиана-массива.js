function медиана(данные) {
  if (данные.length === 0) return null;
  const упорядоченные = [...данные].sort((левое, правое) => левое - правое);
  const середина = Math.floor(упорядоченные.length / 2);
  return упорядоченные.length % 2 ? упорядоченные[середина] : (упорядоченные[середина - 1] + упорядоченные[середина]) / 2;
}
console.log(медиана([8, 1, 4]));    // 4
console.log(медиана([8, 1, 4, 6])); // 5

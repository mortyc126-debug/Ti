// Расстояние между точками
// Группа: Расстояния и нормы
// Описание: Находит евклидово расстояние между точками одинаковой размерности.
// Ожидаемый вывод: в консоли: 5
// Пояснения:
//   Корень из суммы квадратов разностей координат.

function расстояние(a, b) {
  if (a.length !== b.length) return null;
  return Math.sqrt(a.reduce((s, x, i) => s + (x - b[i]) ** 2, 0));
}
console.log(расстояние([0, 0], [3, 4]));

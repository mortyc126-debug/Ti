// Расчёт квантиля
// Группа: Статистика
// Описание: Находит квантиль по линейной интерполяции между соседними значениями.
// Ожидаемый вывод: в консоли: 17.5
// Пояснения:
//   p — квантильный уровень от 0 до 1; например 0.25 соответствует 25%-му уровню.
//   Дробная позиция в отсортированном массиве.

function квантиль(данные, p) {
  if (!данные.length || p < 0 || p > 1) return null;
  const x = [...данные].sort((a, b) => a - b);
  const позиция = (x.length - 1) * p;
  const слева = Math.floor(позиция);
  const доля = позиция - слева;
  return x[слева] + (x[Math.min(слева + 1, x.length - 1)] - x[слева]) * доля;
}
console.log(квантиль([10, 20, 30, 40], 0.25));

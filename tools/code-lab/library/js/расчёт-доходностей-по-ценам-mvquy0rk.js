// Расчёт доходностей по ценам
// Группа: Временные ряды
// Описание: Преобразует последовательность цен в простые доходности между соседними наблюдениями.
// Ожидаемый вывод: в консоли: [0.1, -0.1]
// Пояснения:
//   P_t / P_(t-1) - 1; значение 0.1 означает +10%.
//   Неопределённая доходность при нулевой предыдущей цене.

function доходности(цены) {
  const результат = [];
  for (let i = 1; i < цены.length; i++) {
    if (цены[i - 1] === 0) результат.push(null);
    else результат.push(цены[i] / цены[i - 1] - 1);
  }
  return результат;
}
console.log(доходности([100, 110, 99]));

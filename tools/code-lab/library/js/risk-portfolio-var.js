// w — веса бумаг [0.5, 0.5]; cov — матрица ковариаций N×N
function дисперсияПортфеля(w, cov){
  let сумма = 0;
  for(let i = 0; i < w.length; i++){
    for(let j = 0; j < w.length; j++){
      сумма += w[i] * w[j] * cov[i][j]; // вклад пары (i,j)
    }
  }
  return сумма;                        // дисперсия; корень = волатильность
}
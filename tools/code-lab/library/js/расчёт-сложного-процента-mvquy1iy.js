// Расчёт сложного процента
// Группа: Проценты и темпы изменения
// Описание: Рассчитывает итоговую сумму при периодическом начислении сложного процента.
// Ожидаемый вывод: в консоли: 1157.625
// Пояснения:
//   Ставка за один период в долях: 0.05 означает 5%.
//   Количество периодов начисления.

function сложныйПроцент(капитал, ставка, периоды) {
  return капитал * (1 + ставка) ** периоды;
}
console.log(сложныйПроцент(1000, 0.05, 3));

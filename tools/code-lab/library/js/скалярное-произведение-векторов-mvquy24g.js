// Скалярное произведение векторов
// Группа: Векторы и матрицы
// Описание: Вычисляет скалярное произведение двух векторов.
// Ожидаемый вывод: в консоли: 32
// Пояснения:
//   Сумма попарных произведений элементов двух векторов.

function скалярноеПроизведение(a, b) {
  if (a.length !== b.length) return null;
  return a.reduce((s, x, i) => s + x * b[i], 0);
}
console.log(скалярноеПроизведение([1, 2, 3], [4, 5, 6]));

const цены = [100, 102, 101, 105, 103, 108];

// шаг 1: массив цен → массив доходностей
function доходности(цены){
  const out = [];
  for(let i = 1; i < цены.length; i++) out.push(цены[i] / цены[i - 1] - 1);
  return out;
}
// шаг 2: массив доходностей → одно число (риск)
function волатильность(дох){
  const среднее = дох.reduce((a, b) => a + b, 0) / дох.length;
  const дисп = дох.reduce((a, b) => a + (b - среднее) * (b - среднее), 0) / дох.length;
  return Math.sqrt(дисп);
}

const дох = доходности(цены);       // провод: массив доходностей
const риск = волатильность(дох);    // дох ВХОДИТ сюда → число
console.log("риск:", риск.toFixed(4));
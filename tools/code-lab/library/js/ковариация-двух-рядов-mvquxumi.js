// Ковариация двух рядов
// Группа: Корреляция и зависимость
// Описание: Вычисляет ковариацию генеральной совокупности двух рядов.
// Ожидаемый вывод: в консоли: 1.3333333333333333
// Пояснения:
//   Показывает совместное изменение рядов; величина зависит от единиц измерения.

function ковариация(x, y) {
  if (x.length !== y.length || x.length === 0) return null;
  const mx = x.reduce((s, v) => s + v, 0) / x.length;
  const my = y.reduce((s, v) => s + v, 0) / y.length;
  return x.reduce((s, v, i) => s + (v - mx) * (y[i] - my), 0) / x.length;
}
console.log(ковариация([1, 2, 3], [2, 4, 6]));

// Среднее арифметическое
// Группа: Среднее значение
// Описание: Вычисляет среднее арифметическое массива чисел.
// Ожидаемый вывод: в консоли: 25
// Пояснения:
//   reduce — вычисляет сумму элементов.
//   length — количество элементов массива.

const числа = [10, 20, 30, 40];
const среднее = числа.reduce((сумма, x) => сумма + x, 0) / числа.length;
console.log(среднее);

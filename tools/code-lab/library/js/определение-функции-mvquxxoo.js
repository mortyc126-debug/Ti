// Определение функции
// Группа: Условия и циклы
// Описание: Создаёт функцию и вызывает её.
// Ожидаемый вывод: 5; 6
// Пояснения:
//   => — стрелочная запись функции.

function сложить(a, b) {
  return a + b;
}
const умножить = (a, b) => a * b;
console.log(сложить(2, 3));
console.log(умножить(2, 3));

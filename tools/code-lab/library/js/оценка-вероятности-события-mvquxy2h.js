// Оценка вероятности события
// Группа: Вероятность
// Описание: Вычисляет эмпирическую вероятность события по количеству успехов и испытаний.
// Ожидаемый вывод: в консоли: 0.37
// Пояснения:
//   Оценка доли успехов в наблюдавшихся испытаниях, а не гарантия будущего результата.

function вероятность(успехи, испытания) {
  if (испытания <= 0 || успехи < 0 || успехи > испытания) return null;
  return успехи / испытания;
}
console.log(вероятность(37, 100));

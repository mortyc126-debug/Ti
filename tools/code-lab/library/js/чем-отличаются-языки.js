// ЗАЧЕМ РАЗНЫЕ ЯЗЫКИ: под разные задачи и разные компромиссы
// (скорость написания ↔ скорость работы ↔ безопасность ↔ где запускается).

// JavaScript — единственный язык браузера. Поэтому весь твой сайт на нём.
//  + запускается везде, где есть браузер; быстро писать; огромная экосистема.
//  − вольности с типами ("5" + 1 = "51"); легко выстрелить в ногу; числа
//    с плавающей точкой (0.1 + 0.2 ≠ 0.3) — для денег считай в копейках.
//  где: сайты, интерфейсы, Node-серверы.

// Python — «исполнительный язык» расчётов и скриптов. Твой бот — на нём.
//  + очень читаемый; numpy/pandas для математики; быстро прототипировать.
//  − медленный сам по себе (тяжёлое считают библиотеки на C под капотом);
//    отступы — часть синтаксиса (сдвинул строку — сломал логику).
//  где: анализ данных, бэктесты, автоматизация, ML.

// SQL — не про «как», а про «что»: описываешь, какие данные хочешь.
//  + идеален для выборок/агрегаций по таблицам; база сама оптимизирует.
//  − только данные (не напишешь на нём интерфейс); у каждой СУБД свой диалект.
//  где: запросы к базам данных.

// HTML/CSS — не языки программирования: разметка и стиль.
//  HTML — ЧТО на странице (структура), CSS — КАК выглядит (цвет/размер/сетка).
//  логики нет — её добавляет JS.

// C / Rust — «близко к железу», максимум скорости и контроля памяти.
//  + очень быстро; на них написаны Python/браузеры внутри.
//  − долго и опасно писать (C) либо строгий компилятор ругается (Rust).
//  где: системное, игры, движки, то что под капотом.

// ПРАВИЛО ВЫБОРА: язык диктует ЗАДАЧА и ГДЕ код запускается.
//  в браузере — только JS; расчёты/данные — Python; выборки из базы — SQL.

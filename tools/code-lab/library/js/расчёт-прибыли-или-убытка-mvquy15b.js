// Расчёт прибыли или убытка
// Группа: Исполнение сделок
// Описание: Рассчитывает денежный результат длинной или короткой позиции без комиссий.
// Ожидаемый вывод: 16; 16
// Пояснения:
//   Profit and Loss — прибыль или убыток.
//   Стоимость одного пункта изменения цены на единицу позиции; комиссии и проскальзывание не учтены.

function pnl(направление, вход, выход, количество, множитель = 1) {
  if (![вход, выход, количество, множитель].every(Number.isFinite) || количество < 0) return null;
  const знак = направление === "long" ? 1 : направление === "short" ? -1 : null;
  if (знак === null) return null;
  return знак * (выход - вход) * количество * множитель;
}
console.log(pnl("long", 100, 108, 2));   // 16
console.log(pnl("short", 100, 92, 2));   // 16

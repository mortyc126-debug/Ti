function сочетания(всего, выбрано) {
  if (!Number.isInteger(всего) || !Number.isInteger(выбрано) || всего < 0 || выбрано < 0 || выбрано > всего) return null;
  выбрано = Math.min(выбрано, всего - выбрано);
  let результат = 1;
  for (let множитель = 1; множитель <= выбрано; множитель++) результат = результат * (всего - выбрано + множитель) / множитель;
  return Math.round(результат);
}
console.log(сочетания(5, 2));

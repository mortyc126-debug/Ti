// Взвешенное среднее
// Группа: Среднее значение
// Описание: Вычисляет среднее с учётом веса каждого наблюдения.
// Ожидаемый вывод: в консоли: 22.5
// Пояснения:
//   Вес задаёт вклад наблюдения в итог.
//   Сумма весов; должна быть ненулевой.

const значения = [10, 20, 40];
const веса = [1, 2, 1];
const числитель = значения.reduce((s, x, i) => s + x * веса[i], 0);
const знаменатель = веса.reduce((s, w) => s + w, 0);
console.log(числитель / знаменатель);

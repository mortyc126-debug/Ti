// Волатильность доходностей
// Группа: Риск и метрики
// Описание: Оценивает волатильность как стандартное отклонение периодических доходностей.
// Ожидаемый вывод: ≈ 0.01247 (1.247% за период)
// Пояснения:
//   Стандартное отклонение доходностей; годовое значение требует отдельного коэффициента масштабирования.

function волатильность(доходности) {
  if (!доходности.length) return null;
  const среднее = доходности.reduce((s, r) => s + r, 0) / доходности.length;
  const дисперсия = доходности.reduce((s, r) => s + (r - среднее) ** 2, 0) / доходности.length;
  return Math.sqrt(дисперсия);
}
console.log(волатильность([0.01, -0.01, 0.02]));

// Нормализация диапазона
// Группа: Нормализация данных
// Описание: Линейно переводит число из одного диапазона в другой.
// Ожидаемый вывод: в консоли: 0.5
// Пояснения:
//   Преобразование масштаба; результат здесь лежит в [0, 1], если x внутри исходного диапазона.

function нормализовать(x, минимум, максимум) {
  if (максимум === минимум) return null;
  return (x - минимум) / (максимум - минимум);
}

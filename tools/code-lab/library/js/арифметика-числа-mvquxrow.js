// Арифметика числа
// Группа: Числа и простые операции
// Описание: Вычисляет базовые арифметические выражения.
// Ожидаемый вывод: 17; 7; 60; 2.4; 2; 144
// Пояснения:
//   % — остаток от деления; полезен для проверки кратности.
//   ** — возведение в степень.

const a = 12;
const b = 5;
console.log(a + b); // 17
console.log(a - b); // 7
console.log(a * b); // 60
console.log(a / b); // 2.4
console.log(a % b); // 2
console.log(a ** 2); // 144

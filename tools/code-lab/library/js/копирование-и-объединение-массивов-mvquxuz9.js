// Копирование и объединение массивов
// Группа: Массивы
// Описание: Копирует массив и склеивает несколько массивов.
// Ожидаемый вывод: [ 1, 2 ]; [ 1, 2, 3, 4 ]
// Пояснения:
//   Оператор ... разворачивает элементы массива.

const a = [1, 2];
const b = [3, 4];
const копия = [...a];
const вместе = [...a, ...b];
console.log(копия);
console.log(вместе);

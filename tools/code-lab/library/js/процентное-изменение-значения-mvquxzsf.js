// Процентное изменение значения
// Группа: Проценты и темпы изменения
// Описание: Вычисляет относительное изменение между начальным и конечным значением.
// Ожидаемый вывод: в консоли: 15
// Пояснения:
//   Изменение, делённое на модуль исходного значения, умноженное на 100%.

function процентноеИзменение(начало, конец) {
  if (начало === 0) return null;
  return (конец - начало) / Math.abs(начало) * 100;
}
console.log(процентноеИзменение(80, 92));

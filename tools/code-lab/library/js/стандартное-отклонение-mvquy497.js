// Стандартное отклонение
// Группа: Статистика
// Описание: Вычисляет стандартное отклонение генеральной совокупности.
// Ожидаемый вывод: ≈ 1.633
// Пояснения:
//   Math.sqrt — квадратный корень.
//   Корень из дисперсии; измеряется в тех же единицах, что и данные.

function стандартноеОтклонение(данные) {
  if (данные.length === 0) return null;
  const среднее = данные.reduce((s, x) => s + x, 0) / данные.length;
  const дисперсия = данные.reduce((s, x) => s + (x - среднее) ** 2, 0) / данные.length;
  return Math.sqrt(дисперсия);
}
console.log(стандартноеОтклонение([2, 4, 6]));

// 1) ВНУТРИ ОДНОГО ДВИЖКА — файлы одного мира соединяются импортами.
//    Браузер понимает HTML+CSS+JS сразу, поэтому один .html МОЖЕТ держать
//    и <style> (стиль), и <script> (логику) — это реальное «вложение».
//    JS-файлы между собой: export / import. Python-файлы: import.
//    НО Python внутри JS внутри HTML «в одном запуске» — НЕЛЬЗЯ:
//    браузер не умеет Python.
//    (Исключение: PyScript / Pyodide — Python компилируют в WebAssembly,
//     и он бежит в браузере. Экзотика, медленно, редко нужно.)

// 2) РАЗНЫЕ ЯЗЫКИ / МАШИНЫ — отдельные программы, которые ОБЩАЮТСЯ.
//    Никто не вложен в другого. Способы общения:
//    • HTTP + JSON — один шлёт запрос, другой отвечает данными (fetch).
//    • общий файл — один пишет .json/.csv, другой читает.
//    • база данных — один кладёт строки, другой забирает.
//    Главное — ДОГОВОР (формат сообщения), а не общий код.

// ТВОЙ ПРОЕКТ ИМЕННО ТАК И УСТРОЕН:
//   [браузер: HTML+JS сайт] --HTTP/JSON--> [Cloudflare Worker (JS)] --> ГИР БО
//   [браузер]               --HTTP------->  [MOEX API]
//   [Python-бот]            --файлы/JSON-->  общие данные --> [сайт читает]
//   каждый кусок на своём языке, связаны СООБЩЕНИЯМИ, не общим кодом.
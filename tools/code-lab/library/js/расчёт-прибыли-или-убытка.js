function результатСделки(направление, вход, выход, количество, множитель = 1) {
  if (![вход, выход, количество, множитель].every(Number.isFinite) || количество < 0) return null;
  const знак = направление === "покупка" ? 1 : направление === "продажа" ? -1 : null;
  if (знак === null) return null;
  return знак * (выход - вход) * количество * множитель;
}
console.log(результатСделки("покупка", 100, 108, 2));   // 16
console.log(результатСделки("продажа", 100, 92, 2));   // 16

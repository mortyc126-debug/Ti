// Число сочетаний
// Группа: Комбинаторика
// Описание: Вычисляет число сочетаний C(n, k) без учёта порядка.
// Ожидаемый вывод: в консоли: 10
// Пояснения:
//   Число способов выбрать k объектов из n, когда порядок не важен.
//   Убирает возможную малую погрешность вычислений с плавающей точкой.

function сочетания(n, k) {
  if (!Number.isInteger(n) || !Number.isInteger(k) || n < 0 || k < 0 || k > n) return null;
  k = Math.min(k, n - k);
  let результат = 1;
  for (let i = 1; i <= k; i++) результат = результат * (n - k + i) / i;
  return Math.round(результат);
}
console.log(сочетания(5, 2));

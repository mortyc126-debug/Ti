// Часть строки
// Группа: Строки
// Описание: Вырезает фрагмент строки по индексам.
// Ожидаемый вывод: Привет; мир
// Пояснения:
//   slice(от, до) — до не включается; отрицательные индексы считаются с конца.

const текст = 'Привет, мир';
console.log(текст.slice(0, 6));
console.log(текст.slice(-3));

// Сортировка чисел
// Группа: Массивы
// Описание: Сортирует числа по возрастанию и убыванию.
// Ожидаемый вывод: [ 2, 4, 10, 33 ]; [ 33, 10, 4, 2 ]
// Пояснения:
//   Без функции сравнения sort сортирует как строки, поэтому для чисел нужен (a, b) => a - b.

const числа = [10, 2, 33, 4];
console.log([...числа].sort((a, b) => a - b));
console.log([...числа].sort((a, b) => b - a));

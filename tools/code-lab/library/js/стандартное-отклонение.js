function стандартноеОтклонение(данные) {
  if (данные.length === 0) return null;
  const среднее = данные.reduce((сумма, значение) => сумма + значение, 0) / данные.length;
  const дисперсия = данные.reduce((сумма, значение) => сумма + (значение - среднее) ** 2, 0) / данные.length;
  return Math.sqrt(дисперсия);
}
console.log(стандартноеОтклонение([2, 4, 6]));

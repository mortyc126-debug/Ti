function ковариация(первыйРяд, второйРяд) {
  if (первыйРяд.length !== второйРяд.length || первыйРяд.length === 0) return null;
  const среднееПервого = первыйРяд.reduce((сумма, значение) => сумма + значение, 0) / первыйРяд.length;
  const среднееВторого = второйРяд.reduce((сумма, значение) => сумма + значение, 0) / второйРяд.length;
  return первыйРяд.reduce((сумма, значение, индекс) => сумма + (значение - среднееПервого) * (второйРяд[индекс] - среднееВторого), 0) / первыйРяд.length;
}
console.log(ковариация([1, 2, 3], [2, 4, 6]));

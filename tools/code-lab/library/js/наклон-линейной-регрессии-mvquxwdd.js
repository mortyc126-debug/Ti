// Наклон линейной регрессии
// Группа: Регрессия
// Описание: Находит наклон простой линейной регрессии y на x методом наименьших квадратов.
// Ожидаемый вывод: в консоли: 2
// Пояснения:
//   Метод наименьших квадратов подбирает линию, минимизируя сумму квадратов остатков.
//   Ожидаемое изменение y при увеличении x на одну единицу в рамках линейной модели.

function наклонРегрессии(x, y) {
  if (x.length !== y.length || x.length < 2) return null;
  const mx = x.reduce((s, v) => s + v, 0) / x.length;
  const my = y.reduce((s, v) => s + v, 0) / y.length;
  let числитель = 0, знаменатель = 0;
  for (let i = 0; i < x.length; i++) {
    числитель += (x[i] - mx) * (y[i] - my);
    знаменатель += (x[i] - mx) ** 2;
  }
  return знаменатель === 0 ? null : числитель / знаменатель;
}
console.log(наклонРегрессии([1, 2, 3], [3, 5, 7]));

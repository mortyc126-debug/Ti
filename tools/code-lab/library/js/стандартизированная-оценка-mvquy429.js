// Стандартизированная оценка
// Группа: Нормализация данных
// Описание: Показывает, на сколько стандартных отклонений значение отстоит от среднего.
// Ожидаемый вывод: в консоли: 2
// Пояснения:
//   Стандартизированное отклонение значения от среднего.

function zОценка(x, среднее, отклонение) {
  if (отклонение <= 0) return null;
  return (x - среднее) / отклонение;
}
console.log(zОценка(14, 10, 2));

// Корреляция двух рядов
// Группа: Корреляция и зависимость
// Описание: Вычисляет коэффициент корреляции Пирсона для двух массивов одинаковой длины.
// Ожидаемый вывод: в консоли: 1
// Пояснения:
//   Корреляция Пирсона измеряет линейную связь в диапазоне от -1 до 1.
//   Возвращается, если длины не совпадают, наблюдений мало или один ряд постоянный.

function корреляция(x, y) {
  if (x.length !== y.length || x.length < 2) return null;
  const mx = x.reduce((s, v) => s + v, 0) / x.length;
  const my = y.reduce((s, v) => s + v, 0) / y.length;
  let числитель = 0, xx = 0, yy = 0;
  for (let i = 0; i < x.length; i++) {
    const dx = x[i] - mx, dy = y[i] - my;
    числитель += dx * dy;
    xx += dx * dx;
    yy += dy * dy;
  }
  return xx === 0 || yy === 0 ? null : числитель / Math.sqrt(xx * yy);
}
console.log(корреляция([1, 2, 3], [2, 4, 6]));

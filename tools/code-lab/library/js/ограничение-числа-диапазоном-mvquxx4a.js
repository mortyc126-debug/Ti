// Ограничение числа диапазоном
// Группа: Диапазоны и ограничения
// Описание: Ограничивает число заданными нижней и верхней границами.
// Ожидаемый вывод: 10; 0; 6
// Пояснения:
//   Сначала поднимает значение не ниже минимума.
//   Затем опускает значение не выше максимума.

const ограничить = (x, минимум, максимум) =>
  Math.min(Math.max(x, минимум), максимум);

console.log(ограничить(15, 0, 10));  // 10
console.log(ограничить(-4, 0, 10)); // 0
console.log(ограничить(6, 0, 10));  // 6

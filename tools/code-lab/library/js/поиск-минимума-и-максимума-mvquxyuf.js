// Поиск минимума и максимума
// Группа: Минимум и максимум
// Описание: Находит наименьшее и наибольшее из чисел.
// Ожидаемый вывод: -3; 21
// Пояснения:
//   Math.min — находит минимальный аргумент.
//   Math.max — находит максимальный аргумент.
//   Оператор spread передаёт элементы массива отдельными аргументами.

const числа = [12, -3, 8, 21, 4];
console.log(Math.min(...числа)); // -3
console.log(Math.max(...числа)); // 21

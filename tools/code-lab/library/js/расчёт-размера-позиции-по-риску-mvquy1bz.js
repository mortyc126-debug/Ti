// Расчёт размера позиции по риску
// Группа: Риск и метрики
// Описание: Оценивает размер позиции по денежному лимиту риска и расстоянию до стопа.
// Ожидаемый вывод: в консоли: 100
// Пояснения:
//   Доля капитала, например 0.01 для 1%.
//   Теоретический максимум по заданному риску; учитывайте шаг лота, маржу, комиссии и гэпы.

function размерПозиции(капитал, рискДоля, вход, стоп, стоимостьПункта = 1) {
  const рискДеньгами = капитал * рискДоля;
  const рискНаЕдиницу = Math.abs(вход - стоп) * стоимостьПункта;
  if (рискДеньгами < 0 || рискНаЕдиницу <= 0) return null;
  return Math.floor(рискДеньгами / рискНаЕдиницу);
}
console.log(размерПозиции(100000, 0.01, 200, 190));

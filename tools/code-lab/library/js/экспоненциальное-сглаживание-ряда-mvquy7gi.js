// Экспоненциальное сглаживание ряда
// Группа: Временные ряды
// Описание: Обновляет экспоненциально сглаженную оценку новым наблюдением.
// Ожидаемый вывод: в консоли: 103
// Пояснения:
//   Коэффициент от 0 до 1: чем он выше, тем больше вес нового наблюдения.

function сглаживание(предыдущее, наблюдение, альфа) {
  if (альфа < 0 || альфа > 1) return null;
  return альфа * наблюдение + (1 - альфа) * предыдущее;
}
console.log(сглаживание(100, 110, 0.3));

// Историческая оценка риска
// Группа: Риск и метрики
// Описание: Оценивает исторический VaR по эмпирическому квантилю доходностей.
// Ожидаемый вывод: в консоли: 0.02
// Пояснения:
//   Value at Risk — порог убытка для заданного уровня и выбранного метода оценки.
//   Оценка по прошлым наблюдениям; зависит от выборки, определения квантиля и горизонта.

function историческийVaR(доходности, уровень = 0.95) {
  if (!доходности.length || уровень <= 0 || уровень >= 1) return null;
  const убытки = доходности.map(r => -r).sort((a, b) => a - b);
  const индекс = Math.min(убытки.length - 1, Math.ceil(уровень * убытки.length) - 1);
  return убытки[индекс];
}
console.log(историческийVaR([-0.02, 0.01, -0.05, 0.03, -0.01], 0.8));

// Размах числового ряда
// Группа: Разброс данных
// Описание: Находит размах массива чисел.
// Ожидаемый вывод: в консоли: 9
// Пояснения:
//   Разность максимума и минимума; чувствителен к выбросам.

function размах(данные) {
  if (!данные.length) return null;
  return Math.max(...данные) - Math.min(...данные);
}
console.log(размах([7, 2, 11, 5]));

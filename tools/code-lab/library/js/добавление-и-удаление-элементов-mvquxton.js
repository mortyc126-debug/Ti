// Добавление и удаление элементов
// Группа: Массивы
// Описание: Меняет массив с конца и с начала.
// Ожидаемый вывод: [ 1, 2, 3, 4 ]; [ 1, 2, 3 ]; [ 0, 1, 2, 3 ]; [ 1, 2, 3 ]
// Пояснения:
//   push и pop — добавить и удалить в конце.
//   unshift и shift — добавить и удалить в начале.

const числа = [1, 2, 3];
числа.push(4);
console.log(числа);
числа.pop();
console.log(числа);
числа.unshift(0);
console.log(числа);
числа.shift();
console.log(числа);

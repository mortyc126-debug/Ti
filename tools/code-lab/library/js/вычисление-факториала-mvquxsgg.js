// Вычисление факториала
// Группа: Комбинаторика
// Описание: Вычисляет факториал неотрицательного целого числа.
// Ожидаемый вывод: в консоли: 120
// Пояснения:
//   n! — произведение целых чисел от 1 до n; 0! = 1.

function факториал(n) {
  if (!Number.isInteger(n) || n < 0) return null;
  let результат = 1;
  for (let i = 2; i <= n; i++) результат *= i;
  return результат;
}
console.log(факториал(5));

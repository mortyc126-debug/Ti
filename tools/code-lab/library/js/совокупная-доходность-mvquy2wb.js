// Совокупная доходность
// Группа: Метрики доходности
// Описание: Находит совокупную доходность последовательности доходностей.
// Ожидаемый вывод: в консоли: -0.009999999999999898 (примерно -1%)
// Пояснения:
//   Доходности периодов перемножаются через множители (1 + r), а не складываются.

function совокупнаяДоходность(доходности) {
  return доходности.reduce((множитель, r) => множитель * (1 + r), 1) - 1;
}
console.log(совокупнаяДоходность([0.1, -0.1]));

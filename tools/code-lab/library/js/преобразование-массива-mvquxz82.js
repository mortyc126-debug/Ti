// Преобразование массива
// Группа: Массивы
// Описание: Создаёт новый массив, применяя функцию к каждому элементу.
// Ожидаемый вывод: [ 2, 4, 6 ]
// Пояснения:
//   map — возвращает новый массив, исходный не меняется.

const числа = [1, 2, 3];
const удвоенные = числа.map(x => x * 2);
console.log(удвоенные);

function квантиль(данные, уровень) {
  if (!данные.length || уровень < 0 || уровень > 1) return null;
  const упорядоченные = [...данные].sort((левое, правое) => левое - правое);
  const позиция = (упорядоченные.length - 1) * уровень;
  const слева = Math.floor(позиция);
  const доля = позиция - слева;
  return упорядоченные[слева] + (упорядоченные[Math.min(слева + 1, упорядоченные.length - 1)] - упорядоченные[слева]) * доля;
}
console.log(квантиль([10, 20, 30, 40], 0.25));

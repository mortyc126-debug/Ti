// Сумма квадратов чисел
// Группа: Числа и простые операции
// Описание: Вычисляет сумму квадратов чисел массива.
// Ожидаемый вывод: в консоли: 14
// Пояснения:
//   Сумма x²; используется, например, в расчёте дисперсии и нормы вектора.

const числа = [1, 2, 3];
const суммаКвадратов = числа.reduce((s, x) => s + x ** 2, 0);
console.log(суммаКвадратов);

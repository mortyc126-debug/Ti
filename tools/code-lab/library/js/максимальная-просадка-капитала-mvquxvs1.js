// Максимальная просадка капитала
// Группа: Риск и метрики
// Описание: Вычисляет максимальную просадку по последовательности значений капитала.
// Ожидаемый вывод: в консоли: 0.3333333333333333 (33.33%)
// Пояснения:
//   Наибольшее падение от предшествующего пика до последующего минимума, в долях.

function максимальнаяПросадка(капитал) {
  if (!капитал.length) return null;
  let пик = капитал[0], максимум = 0;
  for (const значение of капитал) {
    пик = Math.max(пик, значение);
    if (пик > 0) максимум = Math.max(максимум, (пик - значение) / пик);
  }
  return максимум;
}
console.log(максимальнаяПросадка([100, 120, 90, 110, 80, 130]));

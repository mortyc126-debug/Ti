// Сумма элементов массива
// Группа: Агрегация
// Описание: Складывает числа массива в одно значение.
// Ожидаемый вывод: в консоли: 60
// Пояснения:
//   reduce — сворачивает массив в одно значение.
//   итог — накопитель, к которому прибавляется каждый элемент.

const числа = [10, 20, 30];
const сумма = числа.reduce((итог, x) => итог + x, 0);
console.log(сумма);

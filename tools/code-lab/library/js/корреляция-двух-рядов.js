function корреляция(первыйРяд, второйРяд) {
  if (первыйРяд.length !== второйРяд.length || первыйРяд.length < 2) return null;
  const среднееПервого = первыйРяд.reduce((сумма, значение) => сумма + значение, 0) / первыйРяд.length;
  const среднееВторого = второйРяд.reduce((сумма, значение) => сумма + значение, 0) / второйРяд.length;
  let числитель = 0, квадратыПервого = 0, квадратыВторого = 0;
  for (let индекс = 0; индекс < первыйРяд.length; индекс++) {
    const отклонениеПервого = первыйРяд[индекс] - среднееПервого, отклонениеВторого = второйРяд[индекс] - среднееВторого;
    числитель += отклонениеПервого * отклонениеВторого;
    квадратыПервого += отклонениеПервого * отклонениеПервого;
    квадратыВторого += отклонениеВторого * отклонениеВторого;
  }
  return квадратыПервого === 0 || квадратыВторого === 0 ? null : числитель / Math.sqrt(квадратыПервого * квадратыВторого);
}
console.log(корреляция([1, 2, 3], [2, 4, 6]));

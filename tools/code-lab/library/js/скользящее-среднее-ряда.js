function скользящееСреднее(данные, окно) {
  if (!Number.isInteger(окно) || окно < 1 || окно > данные.length) return [];
  const результат = [];
  for (let индекс = окно - 1; индекс < данные.length; индекс++) {
    const часть = данные.slice(индекс - окно + 1, индекс + 1);
    результат.push(часть.reduce((сумма, значение) => сумма + значение, 0) / окно);
  }
  return результат;
}
console.log(скользящееСреднее([1, 2, 3, 4, 5], 3));

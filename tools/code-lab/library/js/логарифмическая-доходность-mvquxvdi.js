// Логарифмическая доходность
// Группа: Временные ряды
// Описание: Вычисляет логарифмическую доходность между двумя положительными ценами.
// Ожидаемый вывод: ≈ 0.09531
// Пояснения:
//   Натуральный логарифм; логарифмические доходности удобно складывать по времени при положительных ценах.

function логДоходность(ценаДо, ценаПосле) {
  if (ценаДо <= 0 || ценаПосле <= 0) return null;
  return Math.log(ценаПосле / ценаДо);
}
console.log(логДоходность(100, 110));

function шагА(){ return 10; }             // выход: 10
function шагБ(вход){ return вход * 2; }   // вход 10 → выход 20
function шагВ(вход){ return вход + 5; }   // вход 20 → выход 25

const а = шагА();      // провод «а» держит 10
const б = шагБ(а);     // отдаём «а» в шагБ → б = 20
const в = шагВ(б);     // отдаём «б» в шагВ → в = 25
console.log(а, б, в);  // 10 20 25
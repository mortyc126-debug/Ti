function волатильность(доходности) {
  if (!доходности.length) return null;
  const среднее = доходности.reduce((сумма, доходность) => сумма + доходность, 0) / доходности.length;
  const дисперсия = доходности.reduce((сумма, доходность) => сумма + (доходность - среднее) ** 2, 0) / доходности.length;
  return Math.sqrt(дисперсия);
}
console.log(волатильность([0.01, -0.01, 0.02]));

// Умножение матрицы на вектор
// Группа: Векторы и матрицы
// Описание: Умножает матрицу на вектор, проверяя размерность.
// Ожидаемый вывод: в консоли: [50, 110]
// Пояснения:
//   Двумерный массив; все строки должны иметь длину, равную длине вектора.
//   map — создаёт результат для каждой строки матрицы.

function матрицаНаВектор(матрица, вектор) {
  if (!матрица.every(строка => строка.length === вектор.length)) return null;
  return матрица.map(строка => строка.reduce((s, x, i) => s + x * вектор[i], 0));
}
console.log(матрицаНаВектор([[1, 2], [3, 4]], [10, 20]));

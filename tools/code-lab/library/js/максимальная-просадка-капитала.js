function максимальнаяПросадка(капитал) {
  if (!капитал.length) return null;
  let пик = капитал[0], максимум = 0;
  for (const значение of капитал) {
    пик = Math.max(пик, значение);
    if (пик > 0) максимум = Math.max(максимум, (пик - значение) / пик);
  }
  return максимум;
}
console.log(максимальнаяПросадка([100, 120, 90, 110, 80, 130]));

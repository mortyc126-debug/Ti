// Свёртка массива
// Группа: Массивы
// Описание: Сводит массив к одному значению через reduce.
// Ожидаемый вывод: 24
// Пояснения:
//   reduce(функция, начальное) — накапливает результат по элементам.

const числа = [1, 2, 3, 4];
const произведение = числа.reduce((acc, x) => acc * x, 1);
console.log(произведение);

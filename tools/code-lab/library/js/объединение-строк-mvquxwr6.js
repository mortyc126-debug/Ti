// Объединение строк
// Группа: Строки
// Описание: Склеивает строки оператором + и шаблонной строкой.
// Ожидаемый вывод: Привет, Анна!; Мне 25 лет
// Пояснения:
//   Шаблонная строка — вставляет значения переменных прямо в текст.

const имя = 'Анна';
const возраст = 25;
console.log('Привет, ' + имя + '!');
console.log(`Мне ${возраст} лет`);

// Замена в строке
// Группа: Строки
// Описание: Заменяет подстроку на другую.
// Ожидаемый вывод: собака и кошка; собака и собака
// Пояснения:
//   replaceAll — заменяет все вхождения, replace — только первое.

const текст = 'кошка и кошка';
console.log(текст.replace('кошка', 'собака'));
console.log(текст.replaceAll('кошка', 'собака'));

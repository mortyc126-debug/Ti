// Округление чисел
// Группа: Округление и точность
// Описание: Округляет число разными способами.
// Ожидаемый вывод: 13; 12; 13; 12.68
// Пояснения:
//   Math.round — округляет до ближайшего целого.
//   toFixed — возвращает строку с заданным числом знаков после точки.

const x = 12.678;
console.log(Math.round(x)); // 13
console.log(Math.floor(x)); // 12
console.log(Math.ceil(x)); // 13
console.log(Number(x.toFixed(2))); // 12.68

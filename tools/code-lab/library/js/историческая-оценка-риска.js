function историческаяОценкаРиска(доходности, уровень = 0.95) {
  if (!доходности.length || уровень <= 0 || уровень >= 1) return null;
  const убытки = доходности.map(доходность => -доходность).sort((левое, правое) => левое - правое);
  const индекс = Math.min(убытки.length - 1, Math.ceil(уровень * убытки.length) - 1);
  return убытки[индекс];
}
console.log(историческаяОценкаРиска([-0.02, 0.01, -0.05, 0.03, -0.01], 0.8));

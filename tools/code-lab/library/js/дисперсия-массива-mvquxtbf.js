// Дисперсия массива
// Группа: Статистика
// Описание: Вычисляет дисперсию генеральной совокупности.
// Ожидаемый вывод: в консоли: 2.6666666666666665
// Пояснения:
//   Среднее квадратов отклонений от среднего.
//   Здесь деление на n: формула для генеральной совокупности, не выборочная оценка.

function дисперсия(данные) {
  if (данные.length === 0) return null;
  const среднее = данные.reduce((s, x) => s + x, 0) / данные.length;
  return данные.reduce((s, x) => s + (x - среднее) ** 2, 0) / данные.length;
}
console.log(дисперсия([2, 4, 6]));

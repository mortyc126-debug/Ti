// Медиана массива
// Группа: Статистика
// Описание: Находит медиану числового массива, не изменяя исходный массив.
// Ожидаемый вывод: 4; 5
// Пояснения:
//   sort — сортирует копию чисел по возрастанию.
//   Медиана — центральное значение упорядоченного ряда; при чётном количестве усредняются два центральных.

function медиана(данные) {
  if (данные.length === 0) return null;
  const x = [...данные].sort((a, b) => a - b);
  const m = Math.floor(x.length / 2);
  return x.length % 2 ? x[m] : (x[m - 1] + x[m]) / 2;
}
console.log(медиана([8, 1, 4]));    // 4
console.log(медиана([8, 1, 4, 6])); // 5

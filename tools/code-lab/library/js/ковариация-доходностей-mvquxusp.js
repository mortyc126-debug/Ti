// Ковариация доходностей
// Группа: Риск портфеля
// Описание: Вычисляет ковариацию двух рядов доходностей.
// Ожидаемый вывод: в консоли: 6.666666666666666e-05
// Пояснения:
//   Совместная изменчивость двух рядов; для портфеля важны также веса активов и дисперсии.

function ковариацияДоходностей(a, b) {
  if (a.length !== b.length || !a.length) return null;
  const ma = a.reduce((s, x) => s + x, 0) / a.length;
  const mb = b.reduce((s, x) => s + x, 0) / b.length;
  return a.reduce((s, x, i) => s + (x - ma) * (b[i] - mb), 0) / a.length;
}
console.log(ковариацияДоходностей([0.01, 0.02, -0.01], [0.02, 0.01, 0]));

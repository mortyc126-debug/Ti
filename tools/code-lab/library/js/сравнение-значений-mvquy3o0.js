// Сравнение значений
// Группа: Условия и циклы
// Описание: Показывает операторы сравнения.
// Ожидаемый вывод: true; false; true; true
// Пояснения:
//   === — строгое равенство без приведения типов; предпочтительнее ==.

console.log(5 > 3);
console.log(5 === '5');
console.log(5 == '5');
console.log(5 !== 3);

// Скользящее среднее ряда
// Группа: Временные ряды
// Описание: Вычисляет простое скользящее среднее для заданного окна.
// Ожидаемый вывод: в консоли: [2, 3, 4]
// Пояснения:
//   Количество последних наблюдений в каждом среднем.
//   slice — берёт копию участка массива, не меняя исходный массив.

function скользящееСреднее(данные, окно) {
  if (!Number.isInteger(окно) || окно < 1 || окно > данные.length) return [];
  const результат = [];
  for (let i = окно - 1; i < данные.length; i++) {
    const часть = данные.slice(i - окно + 1, i + 1);
    результат.push(часть.reduce((s, x) => s + x, 0) / окно);
  }
  return результат;
}
console.log(скользящееСреднее([1, 2, 3, 4, 5], 3));

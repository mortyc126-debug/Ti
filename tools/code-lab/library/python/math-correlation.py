import numpy as np

# Матрица доходностей: строки — активы, столбцы — дни.
доходности = np.array([
    [0.01, -0.02, 0.03],   # актив A
    [0.02, -0.01, 0.025],  # актив B
], dtype=float)

if доходности.ndim != 2 or доходности.shape[0] < 2 or доходности.shape[1] < 2:
    raise ValueError("Нужны минимум два актива и два наблюдения")
if not np.all(np.isfinite(доходности)):
    raise ValueError("Матрица доходностей должна содержать конечные значения")
if np.any(np.std(доходности, axis=1, ddof=1) == 0):
    raise ValueError("Корреляция не определена для постоянного ряда")

корр = np.corrcoef(доходности)   # корреляционная матрица активов
print(корр)

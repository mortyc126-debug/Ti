import math
from math import ceil

доходности = [-0.03, 0.01, -0.01, 0.02, -0.05, 0.015, 0.0, -0.02, 0.03, 0.005]
уровень = 0.95

if not доходности:
    raise ValueError("Для оценки VaR нужна хотя бы одна доходность")
if not math.isfinite(уровень) or not 0 < уровень < 1:
    raise ValueError("Уровень VaR должен быть конечным и находиться между 0 и 1")
if any(not math.isfinite(r) or r < -1 for r in доходности):
    raise ValueError("Доходности должны быть конечными и не меньше -100%")

# Метод ближайшего ранга для нижнего хвоста распределения доходностей.
# На маленькой выборке оценка грубая: при 10 точках VaR 95% равен худшему убытку.
отсортированные = sorted(доходности)
альфа = 1 - уровень
индекс = max(0, ceil(len(отсортированные) * альфа) - 1)
var = -отсортированные[индекс]
print(var)

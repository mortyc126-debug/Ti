import math

def максимальная_просадка(капитал):
    """Максимальная просадка как отрицательная доля от исторического пика."""
    if not капитал:
        raise ValueError("Ряд капитала не должен быть пустым")
    if any(not math.isfinite(float(x)) or x <= 0 for x in капитал):
        raise ValueError("Значения капитала должны быть конечными и положительными")

    пик = float(капитал[0])
    максимальная = 0.0
    for значение in капитал:
        значение = float(значение)
        пик = max(пик, значение)
        просадка = значение / пик - 1
        максимальная = min(максимальная, просадка)
    return максимальная

цены_капитала = [1000, 1100, 1050, 1200, 900, 980]
print(максимальная_просадка(цены_капитала))

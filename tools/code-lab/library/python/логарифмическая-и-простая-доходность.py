import math

цены = [100.0, 105.0, 102.0]
if any(not math.isfinite(цена) or цена <= 0 for цена in цены):
    raise ValueError("Цены должны быть конечными и положительными")

простая = [новая / старая - 1 for старая, новая in zip(цены, цены[1:])]
логарифмическая = [math.log(новая / старая) for старая, новая in zip(цены, цены[1:])]
print(простая)
print(логарифмическая)

import math

w1, w2 = 0.6, 0.4       # веса портфеля; могут быть отрицательными при short-позициях
s1, s2 = 0.20, 0.10     # волатильности за один и тот же период
rho = 0.3               # корреляция доходностей

значения = (w1, w2, s1, s2, rho)
if not all(math.isfinite(x) for x in значения):
    raise ValueError("Веса, волатильности и корреляция должны быть конечными")
if s1 < 0 or s2 < 0:
    raise ValueError("Волатильность не может быть отрицательной")
if not -1 <= rho <= 1:
    raise ValueError("Корреляция должна быть между -1 и 1")
if not math.isclose(w1 + w2, 1.0, abs_tol=1e-9):
    raise ValueError("В этом примере веса должны суммироваться до 1")

variance = (w1 * s1) ** 2 + (w2 * s2) ** 2 + 2 * w1 * w2 * s1 * s2 * rho
# При допустимых волатильностях и корреляции дисперсия неотрицательна;
# max защищает только от микроскопической отрицательной ошибки округления.
risk = math.sqrt(max(variance, 0.0))
print(risk)

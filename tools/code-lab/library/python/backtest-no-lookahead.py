цены = [100.0, 102.0, 101.0, 104.0]
сигналы_на_закрытии = [0, 1, -1, 1]  # 0 = вне рынка, 1 = long, -1 = short

доходности = [цены[i] / цены[i - 1] - 1 for i in range(1, len(цены))]
# Доходность интервала t-1 -> t применяется к сигналу, известному на закрытии t-1.
сигналы_для_интервала = сигналы_на_закрытии[:-1]
стратегические = [s * r for s, r in zip(сигналы_для_интервала, доходности)]
print([round(x, 6) for x in стратегические])

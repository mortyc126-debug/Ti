// Единый словарь видов взаимодействия частей кода. Используется и импортом связей
// из текста, и отрисовкой рёбер в конструкторе, и Описью. Глобальный CODE_RELATIONS.
// Поле kw — синонимы для текстового формата; стрелка '->' всегда = поток данных.
(function(){
  const C = {
    flow:'#3DD9FF',   // поток данных — голубой
    ctrl:'#B45CFF',   // управление/вызовы — фиолетовый
    struct:'#52F2C9', // структура/зависимости — бирюзовый
    variant:'#9090BB',// варианты/дубли — серый
    conflict:'#FF6B6B',// конфликты — красный
    state:'#FF8800',  // состояние/события — оранжевый
    qa:'#FF2D78'      // проверка/ошибки/тесты — розовый
  };
  // group — для группировки в справочнике; dir: 'd' направленная (A→B), 'u' ненаправленная (A—B)
  const R = [
    // поток данных и управление
    { id:'data',     group:'Поток и управление', label:'передаёт данные', kw:['передаёт','передает','поток','данные в','->','→','=>'], color:C.flow, dir:'d', note:'выход A идёт на вход B' },
    { id:'calls',    group:'Поток и управление', label:'вызывает',        kw:['вызывает','зовёт','зовет','calls','вызов'], color:C.ctrl, dir:'d', note:'A вызывает функцию/код B' },
    { id:'callback', group:'Поток и управление', label:'колбэк',          kw:['колбэк','колбек','обратный вызов','callback'], color:C.ctrl, dir:'d', note:'A передаёт B как обратный вызов' },
    { id:'sequence', group:'Поток и управление', label:'порядок (до/после)',kw:['до','перед','потом','затем','порядок','после','sequence'], color:C.flow, dir:'d', note:'A должен выполниться раньше B (без передачи данных)' },

    // зависимости и структура
    { id:'depends',  group:'Зависимости и структура', label:'зависит от', kw:['зависит от','зависит','needs','depends'], color:C.struct, dir:'d', note:'A не работает без B' },
    { id:'imports',  group:'Зависимости и структура', label:'импортирует',kw:['импортирует','подключает','imports','require'], color:C.struct, dir:'d', note:'A подключает модуль/библиотеку B' },
    { id:'extends',  group:'Зависимости и структура', label:'расширяет',  kw:['расширяет','наследует','extends','наследник'], color:C.struct, dir:'d', note:'A наследует B (подкласс)' },
    { id:'implements',group:'Зависимости и структура',label:'реализует',  kw:['реализует','implements','соответствует'], color:C.struct, dir:'d', note:'A реализует интерфейс/контракт B' },
    { id:'contains', group:'Зависимости и структура', label:'содержит',   kw:['содержит','состоит из','включает','contains','композиция'], color:C.struct, dir:'d', note:'A состоит из B (композиция)' },
    { id:'wraps',    group:'Зависимости и структура', label:'оборачивает',kw:['оборачивает','декорирует','wraps','обёртка','обертка'], color:C.struct, dir:'d', note:'A оборачивает/декорирует B' },

    // варианты и конфликты
    { id:'alt',      group:'Варианты и конфликты', label:'альтернатива',  kw:['альтернатива','вместо','или','variant','аналог'], color:C.variant, dir:'u', note:'A и B взаимозаменяемы' },
    { id:'replaces', group:'Варианты и конфликты', label:'заменяет',      kw:['заменяет','устаревает','replaces','новее'], color:C.variant, dir:'d', note:'A заменяет устаревший B' },
    { id:'duplicate',group:'Варианты и конфликты', label:'дубликат',      kw:['дубликат','то же что','duplicate','копия'], color:C.variant, dir:'u', note:'A и B — одно и то же' },
    { id:'conflicts',group:'Варианты и конфликты', label:'конфликтует',   kw:['конфликтует','несовместим','conflicts','ломает'], color:C.conflict, dir:'u', note:'A и B нельзя вместе' },

    // состояние и события
    { id:'mutates',  group:'Состояние и события', label:'меняет',         kw:['меняет','пишет в','изменяет','mutates','записывает'], color:C.state, dir:'d', note:'A меняет состояние/данные B (DOM, хранилище, переменную)' },
    { id:'reads',    group:'Состояние и события', label:'читает',         kw:['читает','reads','получает из'], color:C.state, dir:'d', note:'A читает состояние/данные B' },
    { id:'emits',    group:'Состояние и события', label:'шлёт событие',   kw:['шлёт событие','шлет событие','emits','триггерит','запускает событие'], color:C.state, dir:'d', note:'A испускает событие, на которое реагирует B' },
    { id:'listens',  group:'Состояние и события', label:'слушает',        kw:['слушает','подписан на','listens','реагирует на'], color:C.state, dir:'d', note:'A слушает событие B' },

    // проверка, ошибки, тесты
    { id:'validates',group:'Проверка и качество', label:'проверяет',      kw:['проверяет','валидирует','validates'], color:C.qa, dir:'d', note:'A проверяет корректность B' },
    { id:'handles',  group:'Проверка и качество', label:'ловит ошибки',   kw:['ловит ошибки','обрабатывает ошибки','handles','try-catch для'], color:C.qa, dir:'d', note:'A перехватывает ошибки B' },
    { id:'tests',    group:'Проверка и качество', label:'тестирует',      kw:['тестирует','тест для','tests','проверка для'], color:C.qa, dir:'d', note:'A — тест для B' },
    { id:'example',  group:'Проверка и качество', label:'пример для',     kw:['пример для','демонстрирует','example','показывает'], color:C.qa, dir:'d', note:'A — пример использования B' },
    { id:'configures',group:'Проверка и качество',label:'настраивает',    kw:['настраивает','параметры для','configures','конфигурирует'], color:C.qa, dir:'d', note:'A задаёт настройки/параметры B' }
  ];
  const byId = {}; R.forEach(r => byId[r.id] = r);
  // по ключевому слову (длинные раньше коротких, чтобы «зависит от» > «до»)
  const kwIndex = [];
  R.forEach(r => r.kw.forEach(k => kwIndex.push({ k: k.toLowerCase(), r })));
  kwIndex.sort((a, b) => b.k.length - a.k.length);
  window.CODE_RELATIONS = R;
  window.relationById = id => byId[id] || byId.data;
  window.relationColor = id => (byId[id] || byId.data).color;
  window.relationKwIndex = kwIndex;   // [{k, r}] отсортировано по длине ключа
})();

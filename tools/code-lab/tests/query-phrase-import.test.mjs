import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildLegacyQueryPhraseImport } from '../lib/query-phrase-import.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const sourcePath = path.resolve(HERE, '..', 'public', 'dict', 'synonyms.json');
const source = JSON.parse(await fs.readFile(sourcePath, 'utf8'));
const dry = buildLegacyQueryPhraseImport(source);
assert.equal(dry.stats.sourceKeys, 1707);
assert.equal(dry.stats.sourcePhrases, 11629);
assert.equal(dry.stats.importedPhrases, 11629);
assert.equal(dry.stats.skipped, 0);
assert.equal(dry.stats.uniquePhrases, 10855);
assert.equal(dry.stats.ambiguousPhrases, 675);
assert.equal(dry.stats.maxTargetsPerPhrase, 6);
assert.equal(dry.manifest.concepts.length, 0, 'не создавать фиктивные понятия для ключей словаря');
assert.equal(dry.manifest.relations.length, 0);
assert.equal(dry.manifest.queryPhrases[0].targetKey, Object.keys(source)[0]);
assert.equal(dry.manifest.queryPhrases[0].source.file, 'public/dict/synonyms.json');
assert.equal(dry.manifest.queryPhrases[0].source.index, 0);
assert.ok(dry.manifest.queryPhrases.every(x => !Object.hasOwn(x, 'targetConceptId')));
const repeated = buildLegacyQueryPhraseImport(source);
assert.deepEqual(repeated.manifest, dry.manifest, 'ID импорта должны быть стабильными');
const invalid = buildLegacyQueryPhraseImport({ key: ['ok', '', 3] });
assert.equal(invalid.stats.importedPhrases, 1);
assert.equal(invalid.stats.skipped, 2);
console.log('query-phrase-import: legacy dictionary dry-run passed');
